// DFA -> circom circuit generator (backlog A3, real zk-regex).
//
// Emits a Groth16-provable circuit enforcing that private byte arrays match the
// market's From/content DFAs, with a public `binding` signal committing the proof
// to (domain, publicKeyHash, timestamp, nullifier).
//
// Encoding (one-hot DFA simulation, standard zk-regex approach):
//  - state vector: one signal per DFA state per position; exactly one is 1.
//  - byte-class indicators: shared boundary comparators (b < bound_k), classes
//    partition 1..255; byte 0 is padding and self-loops every state.
//  - transitions grouped by (source state -> target): one product per group.
//  - acceptance: accepting states are absorbing in the DFA itself, so the final
//    vector's accepting mass must be exactly 1.

function dfaSection(name, dfa, len) {
  const S = dfa.numStates;
  const K = dfa.classes.length;
  // distinct boundaries for shared comparators: b < bound
  const bounds = [...new Set(dfa.classes.flatMap(([lo, hi]) => [lo, hi + 1]))].sort((a, b) => a - b);
  const boundIdx = new Map(bounds.map((b, i) => [b, i]));

  // per-state transition groups: target -> list of class indices
  const groups = []; // {state, target, classes[]}
  for (let s = 0; s < S; s++) {
    const byTarget = new Map();
    dfa.transitions[s].forEach((t, ci) => {
      if (!byTarget.has(t)) byTarget.set(t, []);
      byTarget.get(t).push(ci);
    });
    for (const [target, cls] of byTarget) groups.push({ state: s, target, classes: cls });
  }

  const L = [];
  const P = (s) => L.push(s);
  P(`// --- ${name}: ${S} states, ${K} byte-classes, ${bounds.length} boundaries, len ${len} ---`);
  P(`signal ${name}State[${len + 1}][${S}];`);
  P(`${name}State[0][0] <== 1;`);
  P(`for (var s = 1; s < ${S}; s++) { ${name}State[0][s] <== 0; }`);
  P(`component ${name}Bits[${len}];`);
  P(`component ${name}Lt[${len}][${bounds.length}];`);
  P(`component ${name}IsZero[${len}];`);
  P(`signal ${name}Grp[${len}][${groups.length}];`);
  P(`signal ${name}Pad[${len}][${S}];`);
  P(`for (var i = 0; i < ${len}; i++) {`);
  P(`  ${name}Bits[i] = Num2Bits(8);`);
  P(`  ${name}Bits[i].in <== ${name}In[i];`);
  P(`  ${name}IsZero[i] = IsZero();`);
  P(`  ${name}IsZero[i].in <== ${name}In[i];`);
  for (let b = 0; b < bounds.length; b++) {
    P(`  ${name}Lt[i][${b}] = LessThan(9);`);
    P(`  ${name}Lt[i][${b}].in[0] <== ${name}In[i];`);
    P(`  ${name}Lt[i][${b}].in[1] <== ${bounds[b]};`);
  }
  P(`}`);
  P(`for (var i = 0; i < ${len}; i++) {`);
  // class indicator k = (b < hi+1) - (b < lo)  [i.e. lo <= b <= hi]
  const classExpr = dfa.classes.map(
    ([lo, hi]) => `(${name}Lt[i][${boundIdx.get(hi + 1)}].out - ${name}Lt[i][${boundIdx.get(lo)}].out)`,
  );
  groups.forEach((g, gi) => {
    const sum = g.classes.map((ci) => classExpr[ci]).join(" + ");
    P(`  ${name}Grp[i][${gi}] <== ${name}State[i][${g.state}] * (${sum});`);
  });
  // padding: byte 0 self-loops every state
  P(`  for (var s = 0; s < ${S}; s++) { ${name}Pad[i][s] <== ${name}IsZero[i].out * ${name}State[i][s]; }`);
  // next state = padding self-loop + incoming groups
  for (let s = 0; s < S; s++) {
    const inc = groups
      .map((g, gi) => (g.target === s ? `${name}Grp[i][${gi}]` : null))
      .filter(Boolean);
    P(`  ${name}State[i+1][${s}] <== ${name}Pad[i][${s}]${inc.length ? " + " + inc.join(" + ") : ""};`);
  }
  P(`}`);
  const acc = dfa.accepting.flatMap((a, s) => (a ? [s] : []));
  P(`signal ${name}Acc <== ${acc.map((s) => `${name}State[${len}][${s}]`).join(" + ")};`);
  P(`${name}Acc === 1;`);
  return L.join("\n  ");
}

/**
 * @param {object|null} fromDfa  DFA for the From pattern (null = no From condition)
 * @param {object} contentDfa    DFA for the content pattern
 */
export function generateCircom(fromDfa, contentDfa, { fromLen = 48, contentLen = 160 } = {}) {
  const fromSection = fromDfa ? dfaSection("from", fromDfa, fromLen) : "// (no From condition)";
  return `pragma circom 2.1.6;

include "circomlib/circuits/bitify.circom";
include "circomlib/circuits/comparators.circom";

// AUTO-GENERATED by dfa-to-circom.mjs — real zk-regex circuit for a headline market
// pattern pair. Proves the private From/content bytes match the market's compiled
// DFAs; \`binding\` publicly commits the proof to (domain, pubkeyHash, timestamp,
// nullifier) so it cannot be replayed for a different email.
template RegexPair() {
${fromDfa ? `  signal input fromIn[${fromLen}]; // private: From address bytes (0-padded)` : ""}
  signal input contentIn[${contentLen}]; // private: matched email field bytes (0-padded)
  signal input binding; // public: keccak(domain, pubkeyHash, timestamp, nullifier) mod p

  ${fromSection}

  ${dfaSection("content", contentDfa, contentLen)}

  // keep the public binding constrained so the optimizer preserves it
  signal bindingSq <== binding * binding;
}

component main {public [binding]} = RegexPair();
`;
}
