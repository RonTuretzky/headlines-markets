#!/usr/bin/env node
// Copies contract ABIs (from forge artifacts) and deployed addresses (from
// deployments/local.json) into src/contracts/gen.ts so the app never drifts
// from the compiled contracts. Run automatically by `npm run dev` / `build`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const out = (name) =>
  JSON.parse(readFileSync(join(root, "contracts", "out", `${name}.sol`, `${name}.json`), "utf8")).abi;

// DEPLOYMENT=gnosis (or local, default) picks which deployment the app targets.
const network = process.env.DEPLOYMENT ?? "local";
const deployment = JSON.parse(readFileSync(join(root, "contracts", "deployments", `${network}.json`), "utf8"));

const abis = {
  MarketFactory: out("MarketFactory"),
  HeadlineMarket: out("HeadlineMarket"),
  FPMM: out("FPMM"),
  ConditionalTokens: out("ConditionalTokens"),
  TestUSDC: out("TestUSDC"),
  DKIMRegistry: out("DKIMRegistry"),
  DKIMVerifier: out("DKIMVerifier"),
};

const ts = `// AUTO-GENERATED by scripts/sync-contracts.mjs — do not edit.
export const deployment = ${JSON.stringify(deployment, null, 2)} as const;

export const abis = ${JSON.stringify(abis, null, 2)} as const;
`;

const dest = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "contracts");
mkdirSync(dest, { recursive: true });
writeFileSync(join(dest, "gen.ts"), ts);
console.log(`synced ABIs + addresses (${network}, chain ${deployment.chainId}) ->`, join(dest, "gen.ts"));
